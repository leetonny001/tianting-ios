#!/usr/bin/env python3
"""Generates Kit/Sources/TiantingAppKit/Theme/Tokens.swift from design/tokens.json (PRD-ui 6.1, 6.3, 6.4; FE-UI-IMP-1).

design/tokens.json is a copy of tianting-web/src/theme/tokens.json, the single source of the design tokens.

  python3 -I scripts/py/gen_tokens.py            write Tokens.swift
  python3 -I scripts/py/gen_tokens.py --check    fail when Tokens.swift or (if the sibling checkout exists) the copy is stale
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "design", "tokens.json")
WEB = os.path.join(ROOT, "..", "tianting-web", "src", "theme", "tokens.json")
OUT = os.path.join(ROOT, "Kit", "Sources", "TiantingAppKit", "Theme", "Tokens.swift")


def camel(name):
    parts = name.replace("-", ".").split(".")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def rgba(value):
    h = value.lstrip("#")
    if len(h) not in (6, 8):
        raise SystemExit("bad color " + value)
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
    return "%d, %d, %d, %.3f" % (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def px(value):
    return value.replace("px", "")


def generate(tokens):
    out = [
        "// Generated by scripts/py/gen_tokens.py from design/tokens.json. Do not edit.",
        "// The only place in the app with color values (AC-UI-22-3; scripts/py/check_sources.py enforces it).",
        "import SwiftUI",
        "import UIKit",
        "",
        "public enum Tokens {",
        "    private nonisolated static func ui(_ r: Int, _ g: Int, _ b: Int, _ a: Double) -> UIColor {",
        "        UIColor(red: CGFloat(r) / 255, green: CGFloat(g) / 255, blue: CGFloat(b) / 255, alpha: CGFloat(a))",
        "    }",
        "",
        "    private nonisolated static func adaptive(_ light: UIColor, _ dark: UIColor) -> Color {",
        "        Color(uiColor: UIColor { $0.userInterfaceStyle == .dark ? dark : light })",
        "    }",
        "",
        "    public enum Palette {",
    ]
    for name, v in tokens["color"].items():
        out.append(
            "        public nonisolated static let %s = adaptive(ui(%s), ui(%s))"
            % (camel(name), rgba(v["light"]), rgba(v["dark"]))
        )
    out.append("    }")
    out.append("")
    out.append("    /// Avatar placeholder colors, the same in light and dark (PRD-ui 6.4).")
    out.append("    public nonisolated static let avatar: [Color] = [")
    for c in tokens["avatar"]:
        out.append("        Color(uiColor: ui(%s))," % rgba(c))
    out.append("    ]")
    out.append("")
    out.append("    public enum FontSize {")
    for k, v in tokens["font"].items():
        if k != "family":
            out.append("        public nonisolated static let %s: CGFloat = %s" % (camel(k), px(v)))
    out.append("    }")
    out.append("")
    out.append("    public enum Space {")
    for k, v in tokens["space"].items():
        out.append("        public nonisolated static let s%s: CGFloat = %s" % (k, px(v)))
    out.append("    }")
    out.append("")
    out.append("    public enum Radius {")
    for k, v in tokens["radius"].items():
        if v.endswith("px"):
            out.append("        public nonisolated static let %s: CGFloat = %s" % (camel(k), px(v)))
    out.append("    }")
    out.append("")
    out.append("    public enum Size {")
    for k, v in tokens["size"].items():
        out.append("        public nonisolated static let %s: CGFloat = %s" % (camel(k), px(v)))
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(SOURCE, encoding="utf-8") as f:
        raw = f.read()
    text = generate(json.loads(raw))
    if "--check" in sys.argv:
        problems = []
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                problems.append("Tokens.swift is stale: run python3 -I scripts/py/gen_tokens.py")
        if os.path.exists(WEB):
            with open(WEB, encoding="utf-8") as f:
                if f.read() != raw:
                    problems.append("design/tokens.json differs from tianting-web/src/theme/tokens.json")
        if problems:
            print("\n".join(problems))
            return 1
        print("tokens: up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
